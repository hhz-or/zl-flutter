/// 汇总四组语料里出现过的字符码点（Unicode code point，非 UTF-16 code unit）。
///
/// 用途：CJK 字体子集化的一个字符来源。`\u{XXXX}` 属性与代理对都由 `runes`
/// 正确展开，因此不会出现半个代理对导致的豆腐块。
///
/// **不含**正文前缀「致：」——那是展示层文案，由 `lib/l10n/app_zh.arb` 提供，
/// 构建脚本会一并扫描 ARB，避免同一份文案在两处硬编码。
///
/// 不依赖 Flutter，可在任意纯 Dart 环境（构建脚本、测试）中调用。
Set<int> corpusCodePoints(InstructionCorpus corpus) {
  final codePoints = <int>{};
  void collect(List<String> sentences) {
    for (final sentence in sentences) {
      codePoints.addAll(sentence.runes);
    }
  }

  collect(corpus.scenes);
  collect(corpus.actions);
  collect(corpus.supplements);
  collect(corpus.easterEggs);
  return codePoints;
}
